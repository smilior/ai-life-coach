/**
 * セッションコンテキストに基づいてシステムプロンプトを生成
 */
export function generateSystemPrompt(context: SessionContext): string {
  let prompt: string;

  // セッション種別に応じたベースプロンプトを選択
  switch (context.sessionType) {
    case "onboarding":
      prompt = ONBOARDING_SYSTEM_PROMPT;
      break;
    case "daily_checkin":
      prompt = DAILY_CHECKIN_SYSTEM_PROMPT;
      break;
    case "weekly_review":
      prompt = WEEKLY_REVIEW_SYSTEM_PROMPT;
      break;
    case "celebration":
      prompt = CELEBRATION_SYSTEM_PROMPT;
      break;
    default:
      prompt = COACHING_SESSION_SYSTEM_PROMPT;
  }

  // コーチトーンの追加
  if (context.userProfile?.tone) {
    prompt += TONE_PROMPTS[context.userProfile.tone];
  }

  // 現在のステップ固有のプロンプトを追加（コーチングセッションの場合）
  if (context.sessionType === "free" && context.currentStep) {
    prompt += getStepSpecificPrompt(context.currentStep);
  }

  // ユーザープロファイル情報を追加
  if (context.userProfile) {
    prompt += generateUserContextPrompt(context.userProfile);
  }

  return prompt;
}

/**
 * ユーザーコンテキストプロンプトを生成
 */
function generateUserContextPrompt(profile: AIUserProfile): string {
  return `

## ユーザー情報
- ニックネーム: ${profile.nickname}
- 目的: ${profile.purpose === "performance" ? "パフォーマンス向上" : profile.purpose === "mental" ? "メンタル安定" : "変革"}
- 価値観: ${profile.values.join("、") || "未設定"}
- 目標: ${profile.goals.join("、") || "未設定"}
${profile.motivation ? `- 動機: ${profile.motivation}` : ""}
${profile.strengths.length > 0 ? `- 強み: ${profile.strengths.join("、")}` : ""}

このユーザー情報を踏まえて、パーソナライズされた対話を心がけてください。`;
}

/**
 * 会話履歴をプロンプト用に整形
 */
export function formatConversationHistory(
  messages: Array<{ role: "user" | "assistant"; content: string }>
): string {
  if (messages.length === 0) return "";

  return messages
    .map((msg) => `${msg.role === "user" ? "ユーザー" : "コーチ"}: ${msg.content}`)
    .join("\n\n");
}

